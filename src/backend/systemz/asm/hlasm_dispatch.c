#include "../systemz_internal.h"

/* One named control section for the module, with its addressing modes,
 * the register equates the printer's operands use, ENTRY for every external
 * function defined here and EXTRN for every function only declared. */
static void emit_module_begin(anvil_strbuf_t *out, const anvil_module_t *mod, const anvil_mainframe_target_desc_t *desc)
{
    char section[16];
    systemz_symbol_name(section, sizeof(section), mod && mod->name && mod->name[0] ? mod->name : "anvil");
    anvil_strbuf_append(out, "***********************************************************************\n");
    anvil_strbuf_appendf(out, "*        GENERATED BY ANVIL FOR %s\n", desc->name);
    anvil_strbuf_append(out, "***********************************************************************\n");
    for (int reg = 0; reg < 16; reg++)
        anvil_strbuf_appendf(out, "R%-7d EQU   %d\n", reg, reg);
    for (int reg = 0; reg < 16; reg++)
        anvil_strbuf_appendf(out, "F%-7d EQU   %d\n", reg, reg);
    anvil_strbuf_appendf(out, "%-8s CSECT\n", section);
    anvil_strbuf_appendf(out, "%-8s AMODE %s\n", section, desc->amode);
    anvil_strbuf_appendf(out, "%-8s RMODE %s\n", section, desc->rmode);
    for (const anvil_func_t *func = mod ? mod->funcs : NULL; func; func = func->next) {
        if (func->is_declaration)
            systemz_emit_external(out, "EXTRN", func->name);
        else if (func->linkage != ANVIL_LINK_INTERNAL)
            systemz_emit_external(out, "ENTRY", func->name);
    }
}

static void emit_module_end(anvil_strbuf_t *out)
{
    anvil_strbuf_append(out, "         END\n");
}

const systemz_asm_ops_t systemz_hlasm_ops = {
    .name = "HLASM",
    .syntax = ANVIL_SYNTAX_HLASM,
    .emit_mir = systemz_emit_mir_ex,
    .emit_globals = systemz_emit_globals,
    .emit_module_begin = emit_module_begin,
    .emit_module_end = emit_module_end,
};
